export function buildQuestions(ageGroup, gender) {
  if (!ageGroup || !gender) return []
  const optsForGender = SKELETONS.map((skel, idx) => {
    const ageOpts = skel.opts[ageGroup]
    if (!ageOpts) return null
    const genderOpts = ageOpts[gender]
    if (!genderOpts) return null
    return {
      id: idx + 1,
      group: GROUPS[skel.group],
      text: skel.ages[ageGroup],
      options: genderOpts
    }
  }).filter(Boolean)
  return optsForGender
}

export const QUESTION_SETS = {}
for (const age of AGE_GROUPS) {
  for (const gen of GENDERS) {
    QUESTION_SETS[`${age.id}-${gen.id}`] = buildQuestions(age.id, gen.id)
  }
}

