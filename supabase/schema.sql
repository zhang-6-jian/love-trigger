-- 1. 测试结果（只存类型，不存具体答案，保护隐私）
create table if not exists public.assessments (
  id bigint generated by default as identity primary key,
  primary_type text not null check (primary_type in ('A', 'B', 'C', 'D', 'E', 'F')),
  secondary_type text not null check (secondary_type in ('A', 'B', 'C', 'D', 'E', 'F')),
  dual boolean not null default false,
  age_group text,
  visitor_id text,
  created_at timestamptz not null default now()
);

-- 2. 好评
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null default '匿名体验官',
  rating int not null check (rating between 1 and 5),
  text text not null check (char_length(text) between 1 and 160),
  tag text,
  base_likes int not null default 0 check (base_likes >= 0),
  created_at timestamptz not null default now()
);

-- 3. 点赞（同一访客对同一好评只能点一次）
create table if not exists public.review_likes (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.reviews(id) on delete cascade,
  visitor_id text not null,
  created_at timestamptz not null default now(),
  unique (review_id, visitor_id)
);

-- 4. 开启行级安全
alter table public.assessments enable row level security;
alter table public.reviews enable row level security;
alter table public.review_likes enable row level security;

drop policy if exists "assessments_insert" on public.assessments;
create policy "assessments_insert" on public.assessments
  for insert to anon, authenticated with check (true);

drop policy if exists "reviews_select" on public.reviews;
create policy "reviews_select" on public.reviews
  for select to anon, authenticated using (true);

drop policy if exists "reviews_insert" on public.reviews;
create policy "reviews_insert" on public.reviews
  for insert to anon, authenticated
  with check (rating between 1 and 5 and char_length(text) between 1 and 160);

drop policy if exists "likes_select" on public.review_likes;
create policy "likes_select" on public.review_likes
  for select to anon, authenticated using (true);

drop policy if exists "likes_insert" on public.review_likes;
create policy "likes_insert" on public.review_likes
  for insert to anon, authenticated with check (true);

drop policy if exists "likes_delete" on public.review_likes;
create policy "likes_delete" on public.review_likes
  for delete to anon, authenticated using (true);

-- 5. 精确授权：结果表只允许写入，不允许公开读取明细
revoke all on public.assessments from anon, authenticated;
grant insert on public.assessments to anon, authenticated;

revoke all on public.reviews from anon, authenticated;
grant select, insert on public.reviews to anon, authenticated;

revoke all on public.review_likes from anon, authenticated;
grant select, insert, delete on public.review_likes to anon, authenticated;

grant usage, select on all sequences in schema public to anon, authenticated;

-- 6. 公开视图：好评（含点赞总数）
create or replace view public.reviews_public as
select
  r.id,
  r.name,
  r.rating,
  r.text,
  r.tag,
  r.base_likes + coalesce(l.like_count, 0) as likes,
  to_char(r.created_at at time zone 'Asia/Shanghai', 'YYYY-MM-DD') as date,
  r.created_at
from public.reviews r
left join (
  select review_id, count(*)::int as like_count
  from public.review_likes
  group by review_id
) l on l.review_id = r.id;

-- 7. 公开视图：类型分布与最近结果（不含访客标识）
create or replace view public.assessment_stats as
select primary_type, count(*)::bigint as total
from public.assessments
group by primary_type;

create or replace view public.assessment_recent as
select id, primary_type, secondary_type, dual, age_group, created_at
from public.assessments
order by created_at desc
limit 200;

create or replace view public.overview_stats as
select
  (select count(*)::bigint from public.assessments) as total_assessments,
  (select count(*)::bigint from public.reviews) as total_reviews;

revoke all on public.reviews_public from anon, authenticated;
revoke all on public.assessment_stats from anon, authenticated;
revoke all on public.assessment_recent from anon, authenticated;
revoke all on public.overview_stats from anon, authenticated;

grant select on public.reviews_public to anon, authenticated;
grant select on public.assessment_stats to anon, authenticated;
grant select on public.assessment_recent to anon, authenticated;
grant select on public.overview_stats to anon, authenticated;

